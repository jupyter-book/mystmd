import { describe, expect, it } from 'vitest';
import { getConversionFns, transformImageNoAltText } from './images';
import { Session } from '../session';

describe('getConversionFns', () => {
  it('unknown extension returns empty list', async () => {
    expect(getConversionFns('.bad', ['.png' as any])).toEqual([]);
  });
  it('known extension with no validExts returns empty list', async () => {
    expect(getConversionFns('.svg', [])).toEqual([]);
  });
  it('known extension with one validExt returns one item', async () => {
    expect(getConversionFns('.svg', ['.png' as any]).length).toEqual(1);
  });
  it('known extension with multiple validExts returns multiple items', async () => {
    expect(getConversionFns('.svg', ['.png', '.pdf', '.jpg'] as any[]).length).toEqual(2);
  });
  it('order of functions depends on order of validExts', async () => {
    expect(getConversionFns('.svg', ['.png', '.pdf'] as any[])).toEqual(
      getConversionFns('.svg', ['.pdf', '.png'] as any[]).reverse(),
    );
  });
});

describe('Test transformImageNoAltText', () => {
  const session = new Session();

  test('image without alt text generates warning', () => {
    const mdast = {
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          align: 'center',
        },
      ],
    };
    const file = new String();
    transformImageNoAltText(session, mdast, file);
    expect(mdast).toEqual({
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          align: 'center',
        },
      ],
    });
    // A warning was created
    expect(file.messages.length).toBe(1);
    expect(file.messages[0].message.includes('missing alt text')).toBe(true);
  });
  test('image without alt text does not generate a warning', () => {
    const mdast = {
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I have alt text',
          align: 'center',
        },
      ],
    };
    const file = new String();
    transformImageNoAltText(session, mdast, file);
    expect(mdast).toEqual({
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I have alt text',
          align: 'center',
        },
      ],
    });
    // A warning was created
    expect(file.messages.length).toBe(0);
  });
  test('image inside captioned figure warns about generated alt text', () => {
    const mdast = {
      type: 'container',
      kind: 'figure',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I don’t have alt text, but I do have a caption',
          data: {
            altTextIsAutoGenerated: true,
          },
        },
        {
          type: 'caption',
          children: [
            {
              type: 'paragraph',
              children: [
                {
                  type: 'text',
                  value: 'I don’t have alt text, but I do have a caption',
                },
              ],
            },
          ],
        },
      ],
      enumerator: '1',
    };
    const file = new String();
    transformImageNoAltText(session, mdast, file);
    expect(mdast).toEqual({
      type: 'container',
      kind: 'figure',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I don’t have alt text, but I do have a caption',
          data: {
            altTextIsAutoGenerated: true,
          },
        },
        {
          type: 'caption',
          children: [
            {
              type: 'paragraph',
              children: [
                {
                  type: 'text',
                  value: 'I don’t have alt text, but I do have a caption',
                },
              ],
            },
          ],
        },
      ],
      enumerator: '1',
    });
    // A warning was created
    expect(file.messages.length).toBe(1);
    expect(file.messages[0].message.includes('was auto-generated')).toBe(true);
  });
  test('image inside output does not generate warning', () => {
    const mdast = {
      type: 'root',
      children: [
        {
          type: 'output',
          children: [
            {
              type: 'image',
              url: 'https://images.com/cats',
              align: 'center',
            },
          ],
        },
      ],
    };
    const file = new String();
    transformImageNoAltText(session, mdast, file);
    expect(mdast).toEqual({
      type: 'root',
      children: [
        {
          type: 'output',
          children: [
            {
              type: 'image',
              url: 'https://images.com/cats',
              align: 'center',
            },
          ],
        },
      ],
    });
    // A warning was created
    expect(file.messages.length).toBe(0);
  });
});
