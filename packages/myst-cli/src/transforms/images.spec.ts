import { describe, expect, it, test } from 'vitest';
import { getConversionFns, transformImageNoAltText } from './images';
import { Session } from '../session';
import { RuleId } from 'myst-common';

describe('getConversionFns', () => {
  it('unknown extension returns empty list', async () => {
    expect(getConversionFns('.bad', ['.png' as any])).toEqual([]);
  });
  it('known extension with no validExts returns empty list', async () => {
    expect(getConversionFns('.svg', [])).toEqual([]);
  });
  it('known extension with one validExt returns one item', async () => {
    expect(getConversionFns('.svg', ['.png' as any]).length).toEqual(1);
  });
  it('known extension with multiple validExts returns multiple items', async () => {
    expect(getConversionFns('.svg', ['.png', '.pdf', '.jpg'] as any[]).length).toEqual(2);
  });
  it('order of functions depends on order of validExts', async () => {
    expect(getConversionFns('.svg', ['.png', '.pdf'] as any[])).toEqual(
      getConversionFns('.svg', ['.pdf', '.png'] as any[]).reverse(),
    );
  });
});

describe('Test transformImageNoAltText', () => {
  test('image without alt text generates warning', () => {
    const session = new Session();
    const file = new String('my-file');
    const mdast = {
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          align: 'center',
        },
      ],
    };
    // AST is not modified
    transformImageNoAltText(session, mdast, file);
    expect(mdast).toEqual({
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          align: 'center',
        },
      ],
    });
    // A warning was created
    let node = mdast.children[0];
    expect(session.getAllWarnings(RuleId.imageHasAltText)).toEqual([
      {
        file: 'my-file',
        message: `missing alt text for ${node.url}`,
        kind: 'warn',
        ruleId: RuleId.imageHasAltText,
      },
    ]);
  });
  test('image with alt text does not generate a warning', () => {
    const session = new Session();
    const file = new String('my-file');
    const mdast = {
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I have alt text',
          align: 'center',
        },
      ],
    };
    transformImageNoAltText(session, mdast, file);
    // AST is not modified
    expect(mdast).toEqual({
      type: 'root',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I have alt text',
          align: 'center',
        },
      ],
    });
    // No warning created
    expect(session.getAllWarnings(RuleId.imageHasAltText)).toEqual([]);
  });
  test('image inside captioned figure warns about generated alt text', () => {
    const session = new Session();
    const file = new String('my-file');
    const mdast = {
      type: 'container',
      kind: 'figure',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I don’t have alt text, but I do have a caption',
          data: {
            altTextIsAutoGenerated: true,
          },
        },
        {
          type: 'caption',
          children: [
            {
              type: 'paragraph',
              children: [
                {
                  type: 'text',
                  value: 'I don’t have alt text, but I do have a caption',
                },
              ],
            },
          ],
        },
      ],
      enumerator: '1',
    };
    transformImageNoAltText(session, mdast, file);
    // AST is not modified
    expect(mdast).toEqual({
      type: 'container',
      kind: 'figure',
      children: [
        {
          type: 'image',
          url: 'https://images.com/cats',
          alt: 'I don’t have alt text, but I do have a caption',
          data: {
            altTextIsAutoGenerated: true,
          },
        },
        {
          type: 'caption',
          children: [
            {
              type: 'paragraph',
              children: [
                {
                  type: 'text',
                  value: 'I don’t have alt text, but I do have a caption',
                },
              ],
            },
          ],
        },
      ],
      enumerator: '1',
    });
    // A warning was created
    let node = mdast.children[0];
    expect(session.getAllWarnings(RuleId.imageAltTextGenerated)).toEqual([
      {
        file: 'my-file',
        message: `alt text for ${node.url} was auto-generated`,
        note: 'You can remove this warning by writing your own alt text',
        kind: 'warn',
        ruleId: RuleId.imageAltTextGenerated,
      },
    ]);
  });
  test('image inside output does not generate warning', () => {
    const session = new Session();
    const file = new String('my-file');
    const mdast = {
      type: 'root',
      children: [
        {
          type: 'output',
          children: [
            {
              type: 'image',
              url: 'https://images.com/cats',
              align: 'center',
            },
          ],
        },
      ],
    };
    transformImageNoAltText(session, mdast, file);
    expect(mdast).toEqual({
      type: 'root',
      children: [
        {
          type: 'output',
          children: [
            {
              type: 'image',
              url: 'https://images.com/cats',
              align: 'center',
            },
          ],
        },
      ],
    });
    // No warning created
    expect(session.getAllWarnings(RuleId.imageHasAltText)).toEqual([]);
  });
});
